#!/bin/sh
# Bundles the extension's engine (extension/engine/engine.js) into one classic
# script exposing the global SchoologyEngine, for the Android app's assets.
# Same bundle as ios/scripts/build-engine.sh; uses the esbuild installed in ios/
# (`npm install` there once). Without it, copies the committed iOS bundle.
# Usage: build-engine.sh <out-file>
set -eu
ANDROID="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$ANDROID/.."
OUT="$1"
ESBUILD="$ROOT/ios/node_modules/.bin/esbuild"
mkdir -p "$(dirname "$OUT")"
if [ -x "$ESBUILD" ]; then
  "$ESBUILD" "$ROOT/extension/engine/engine.js" \
    --bundle --format=iife --global-name=SchoologyEngine --target=chrome100 \
    --legal-comments=none --log-level=warning \
    --banner:js="// GENERATED by android/scripts/build-engine.sh from extension/engine/engine.js. Do not edit." \
    --outfile="$OUT"
else
  echo "warning: esbuild not installed (npm install in ios/); using the committed ios/App/Resources/engine.js" >&2
  cp "$ROOT/ios/App/Resources/engine.js" "$OUT"
fi
