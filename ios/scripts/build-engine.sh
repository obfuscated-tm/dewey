#!/bin/sh
# Bundles the extension's engine (schoology_archiver_extension/engine/engine.js)
# into one classic script, App/Resources/engine.js, exposing the global
# SchoologyEngine. Generated: never edit the output by hand.
# Needs esbuild: `npm install` in ios/ once.
set -eu
IOS="$(cd "$(dirname "$0")/.." && pwd)"
ESBUILD="$IOS/node_modules/.bin/esbuild"
if [ ! -x "$ESBUILD" ]; then
  echo "error: esbuild missing; run 'npm install' in $IOS" >&2
  exit 1
fi
mkdir -p "$IOS/App/Resources"
"$ESBUILD" "$IOS/../schoology_archiver_extension/engine/engine.js" \
  --bundle --format=iife --global-name=SchoologyEngine --target=safari17 \
  --legal-comments=none --log-level=warning \
  --banner:js="// GENERATED by ios/scripts/build-engine.sh from schoology_archiver_extension/engine/engine.js. Do not edit." \
  --outfile="$IOS/App/Resources/engine.js"
